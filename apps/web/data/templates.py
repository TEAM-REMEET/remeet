"""데모 회의 내용(원문·요약·액션 아이템).

build()는 주제별 원문 줄을 받아 문단 번호를 매기고, 각 항목의 근거(refs)를 문단 번호로 연결합니다.
"""
from __future__ import annotations


def build(o: dict) -> dict:
    n = 0
    segments: list[dict] = []
    topics: list[dict] = []
    for i, tp in enumerate(o["topics"]):
        start = n + 1
        for line in tp["lines"]:
            n += 1
            segments.append({"id": n, "text": line})
        topics.append({"id": f"t{i + 1}", "title": tp["title"], "from": start, "to": n, "note": tp["note"], "edited": False})

    def ref(t: int, ln: int) -> list[int]:
        return [topics[t]["from"] + ln]

    approved = o.get("approved", False)
    return {
        "purpose": o["purpose"],
        "core": o["core"],
        "core_edited": False,
        "segments": segments,
        "topics": topics,
        "decisions": [
            {"id": f"d{i + 1}", "text": x["text"], "topic": f"t{x['t'] + 1}", "refs": x.get("refs") or ref(x["t"], x["ln"]), "edited": x.get("edited", False)}
            for i, x in enumerate(o.get("decisions", []))
        ],
        "issues": [
            {"id": f"i{i + 1}", "title": x["title"], "text": x["text"], "topic": f"t{x['t'] + 1}", "refs": x.get("refs") or ref(x["t"], x["ln"]), "to_next": x.get("to_next", False), "moved": x.get("moved", False)}
            for i, x in enumerate(o.get("issues", []))
        ],
        "agenda": [
            ({"id": f"n{i + 1}", "text": a, "issue": None} if isinstance(a, str) else {"id": f"n{i + 1}", "text": a["text"], "issue": a.get("issue")})
            for i, a in enumerate(o.get("agenda", []))
        ],
        "actions": [
            {
                "id": f"a{i + 1}", "title": a["title"], "topic": f"t{a['t'] + 1}",
                "assignee": a.get("who"), "source": (a.get("src", "explicit") if a.get("who") else None),
                "due": a.get("due"), "due_raw": a.get("raw"), "priority": a.get("pri", "보통"), "ai_priority": a.get("ai_pri", a.get("pri", "보통")),
                "refs": a.get("refs") or ref(a["t"], a["ln"]),
                "review": "approved" if approved else a.get("review", "draft"),
                "estimated": a.get("est", False), "need_skills": a.get("need", []), "need_dept": a.get("dept", ""),
                "keep": False, "edited": a.get("edited", False), "manual": False,
                "work": a.get("ws", "todo"), "remind": True, "ext": a.get("ext"),
            }
            for i, a in enumerate(o.get("actions", []))
        ],
        "history": o.get("history") or [{"t": "—", "who": "시스템", "text": "AI 분석 완료, 초안 생성", "changes": []}],
    }


