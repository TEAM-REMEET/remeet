_PLACEHOLDER = re.compile(r"\{([A-Za-z_]+)\}")


def compose(template: str, speaker_mode: str) -> str:
    # {공통 블록} → {화자 모드 블록} 순서로 채움 (공통 블록 안의 {assignee_rule} 등도 함께 채워짐)
    if speaker_mode not in SPEAKER_MODE_PARTS:
        raise ValueError(f"speaker_mode={speaker_mode!r} — {list(SPEAKER_MODES)} 중 하나")
    prompt = template
    for name, block in COMMON_BLOCKS.items():
        prompt = prompt.replace("{" + name + "}", block)
    for name, block in SPEAKER_MODE_PARTS[speaker_mode].items():
        prompt = prompt.replace("{" + name + "}", block)
    left = sorted(set(_PLACEHOLDER.findall(prompt)))
    if left:
        raise KeyError(f"채워지지 않은 프롬프트 자리: {left}")
    return prompt


