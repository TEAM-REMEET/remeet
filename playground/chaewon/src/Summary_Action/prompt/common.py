def format_meeting_info(metadata: dict[str, str]) -> str:
    # metadata: LLM 입력용 회의 정보 (transcript_parser.llm_metadata — 발화자 줄 · user_id 없음)
    return "\n".join(f"- {k}: {v}" for k, v in metadata.items()) or "(없음)"


def format_utterances(utterances: list[dict]) -> str:
    # utterances: [{"utterance_index": int, "llm_name": str | None, "text": str, ...}]
    # 원본 형식과 관계없이 같은 형태 — speaker: "[번호] 김철수: 내용" (동명이인 "[번호] 홍길동A: 내용") / none: "[번호] 내용"
    # 입력 토큰을 줄이기 위해 user_id · 직무 없이 이름만 넘김 (llm_name, transcript_parser.llm_names)
    lines = []
    for u in utterances:
        name = u.get("llm_name")
        speaker = f"{name}: " if name else ""
        lines.append(f"[{u['utterance_index']}] {speaker}{u['text']}")
    return "\n".join(lines) or "(없음)"


def format_transcript_block(utterances: list[dict]) -> str:
    first = utterances[0]["utterance_index"] if utterances else "-"
    last = utterances[-1]["utterance_index"] if utterances else "-"
    return f"# 전사문 (발화 {first}~{last})\n{format_utterances(utterances)}"


def _tag(value) -> str:
    return f"[{value if value is not None else 'null'}]"


def format_summary(summary) -> str:
    # MeetingSummary → 검증 · 재수정 입력용 텍스트 (item_id 포함, 삭제된 항목 제외)
    #   item_id | (섹션별 필드) | 요약문 | 근거 [번호 …]
    lines = []
    for a in summary.active_agendas():
        lines.append(f"## 안건 {a.agenda_id} | {a.agenda_title}")
        for name in ("discussion_background", "major_discussions", "unresolved_issues", "next_meeting_topics"):
            items = [it for it in a.section(name) if it.status != "DELETED"]
            lines.append(f"### {name}" + ("" if items else " (없음)"))
            for it in items:
                ev = ", ".join(map(str, it.evidence_utterance_indices)) or "-"
                if name == "major_discussions":
                    fields = (f"subtopic: {it.subtopic} | {_tag(it.discussion_tag)}{_tag(it.decision_tag)} | "
                              f"assignees: {', '.join(it.assignees) or '[]'} | due: {it.due or 'null'} | ")
                elif name == "discussion_background":
                    fields = ""
                else:
                    fields = f"{_tag(it.tag)} | "
                lines.append(f"- {it.item_id} | {fields}{it.text} | 근거 [{ev}]")
        lines.append("")
    return "\n".join(lines).rstrip() or "(없음)"


def format_issues(issues) -> str:
    # VerificationIssue 목록 → 재수정 입력용 텍스트
    lines = []
    for i in issues:
        target = ", ".join(i.item_ids) or "(항목 없음)"
        agenda = f" · 안건 {i.agenda_id}" if i.agenda_id else ""
        ev = ", ".join(map(str, i.evidence_utterance_indices)) or "-"
        lines.append(f"- {i.issue_id} | {i.issue_type} | 대상: {target}{agenda} | 근거 [{ev}]\n"
                     f"  문제: {i.description}\n  제안: {i.suggestion}")
    return "\n".join(lines) or "(없음)"
